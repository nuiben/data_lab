-- XMOB & Co. — Snowflake schema
-- Run against DATA_LAB database, PUBLIC schema.
-- UUIDs are supplied by Python; no server-side default needed.
-- FK declarations are informational only — Snowflake does not enforce them.

-- ── Reference / Dimension ─────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS MCC_CODE (
    MCC             CHAR(4)         NOT NULL PRIMARY KEY,
    DESCRIPTION     VARCHAR(128)    NOT NULL,
    XMOB_GROUP      VARCHAR(64)     NOT NULL,
    HAS_OVERRIDE    BOOLEAN         NOT NULL DEFAULT FALSE,
    CREATED_AT      TIMESTAMP_LTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS GEOGRAPHY (
    ZIP_CODE        CHAR(5)         NOT NULL PRIMARY KEY,
    CITY            VARCHAR(64)     NOT NULL,
    STATE_ABBR      CHAR(2)         NOT NULL,
    MSA_NAME        VARCHAR(128),
    SERVICE_REGION  VARCHAR(32)     NOT NULL,
    CREATED_AT      TIMESTAMP_LTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS INDUSTRY_SEGMENT (
    SEGMENT_CODE    VARCHAR(8)      NOT NULL PRIMARY KEY,
    NAICS_PREFIX    CHAR(2)         NOT NULL,
    NAME            VARCHAR(64)     NOT NULL,
    CREATED_AT      TIMESTAMP_LTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS MODEL_VERSION (
    MODEL_ID        VARCHAR(16)     NOT NULL PRIMARY KEY,
    NAME            VARCHAR(32)     NOT NULL,
    VERSION         VARCHAR(8)      NOT NULL,
    EFFECTIVE_DATE  DATE            NOT NULL,
    RETIRED_DATE    DATE,
    IS_CURRENT      BOOLEAN         NOT NULL DEFAULT FALSE,
    CREATED_AT      TIMESTAMP_LTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

-- ── Core Entities ─────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS MERCHANT (
    MERCHANT_ID     VARCHAR(36)     NOT NULL PRIMARY KEY,
    COMPANY_NAME    VARCHAR(128)    NOT NULL,
    DBA_NAME        VARCHAR(128),
    EIN             VARCHAR(10),
    MCC             CHAR(4),
    ZIP_CODE        CHAR(5),
    SEGMENT_CODE    VARCHAR(8),
    STATUS          VARCHAR(16)     NOT NULL,
    ONBOARDED_AT    DATE            NOT NULL,
    SOURCE_SYSTEM   VARCHAR(16)     NOT NULL,
    CREATED_AT      TIMESTAMP_LTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS FLEET_CUSTOMER (
    CUSTOMER_ID     VARCHAR(36)     NOT NULL PRIMARY KEY,
    COMPANY_NAME    VARCHAR(128)    NOT NULL,
    DOT_NUMBER      VARCHAR(12),
    FLEET_SIZE      INTEGER         NOT NULL,
    ZIP_CODE        CHAR(5),
    SEGMENT_CODE    VARCHAR(8),
    STATUS          VARCHAR(16)     NOT NULL,
    ONBOARDED_AT    DATE            NOT NULL,
    CREATED_AT      TIMESTAMP_LTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS ACCOUNT (
    ACCOUNT_ID      VARCHAR(36)     NOT NULL PRIMARY KEY,
    MERCHANT_ID     VARCHAR(36),
    CUSTOMER_ID     VARCHAR(36),
    ACCOUNT_TYPE    VARCHAR(16)     NOT NULL,
    ROUTING_NUMBER  CHAR(9),
    STATUS          VARCHAR(16)     NOT NULL,
    OPENED_AT       DATE            NOT NULL,
    SOURCE_SYSTEM   VARCHAR(16)     NOT NULL,
    CREATED_AT      TIMESTAMP_LTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS CARD (
    CARD_ID             VARCHAR(36)     NOT NULL PRIMARY KEY,
    CUSTOMER_ID         VARCHAR(36)     NOT NULL,
    ACCOUNT_ID          VARCHAR(36)     NOT NULL,
    CARD_NUMBER_LAST4   CHAR(4)         NOT NULL,
    CARD_TYPE           VARCHAR(16)     NOT NULL,
    DRIVER_NAME         VARCHAR(128),
    VEHICLE_ID          VARCHAR(32),
    STATUS              VARCHAR(16)     NOT NULL,
    ISSUED_AT           DATE            NOT NULL,
    CREATED_AT          TIMESTAMP_LTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS TXN (
    TRANSACTION_ID      VARCHAR(36)     NOT NULL PRIMARY KEY,
    ACCOUNT_ID          VARCHAR(36)     NOT NULL,
    MERCHANT_ID         VARCHAR(36),
    CARD_ID             VARCHAR(36),
    AMOUNT              NUMBER(12,2)    NOT NULL,
    MCC                 CHAR(4),
    TRANSACTION_TYPE    VARCHAR(16)     NOT NULL,
    STATUS              VARCHAR(16)     NOT NULL,
    TRANSACTED_AT       TIMESTAMP_LTZ   NOT NULL,
    SOURCE_SYSTEM       VARCHAR(16)     NOT NULL,
    CREATED_AT          TIMESTAMP_LTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS SETTLEMENT (
    SETTLEMENT_ID       VARCHAR(36)     NOT NULL PRIMARY KEY,
    ACCOUNT_ID          VARCHAR(36)     NOT NULL,
    BATCH_DATE          DATE            NOT NULL,
    SETTLEMENT_DATE     DATE            NOT NULL,
    GROSS_AMOUNT        NUMBER(14,2)    NOT NULL,
    FEE_AMOUNT          NUMBER(10,2)    NOT NULL DEFAULT 0,
    NET_AMOUNT          NUMBER(14,2)    NOT NULL,
    TRANSACTION_COUNT   INTEGER         NOT NULL,
    SOURCE_SYSTEM       VARCHAR(16)     NOT NULL,
    CREATED_AT          TIMESTAMP_LTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS UNDERWRITING_DECISION (
    DECISION_ID     VARCHAR(36)     NOT NULL PRIMARY KEY,
    MERCHANT_ID     VARCHAR(36),
    CUSTOMER_ID     VARCHAR(36),
    MODEL_ID        VARCHAR(16)     NOT NULL,
    DECISION_DATE   DATE            NOT NULL,
    OUTCOME         VARCHAR(8)      NOT NULL,
    CREDIT_LIMIT    NUMBER(12,2),
    SCORE           NUMBER(6,4),
    CREATED_AT      TIMESTAMP_LTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RISK_SCORE (
    SCORE_ID        VARCHAR(36)     NOT NULL PRIMARY KEY,
    MERCHANT_ID     VARCHAR(36),
    CUSTOMER_ID     VARCHAR(36),
    MODEL_ID        VARCHAR(16)     NOT NULL,
    SCORE_DATE      DATE            NOT NULL,
    SCORE           NUMBER(6,4)     NOT NULL,
    RISK_BAND       VARCHAR(16)     NOT NULL,
    CREATED_AT      TIMESTAMP_LTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS DISPUTE (
    DISPUTE_ID      VARCHAR(36)     NOT NULL PRIMARY KEY,
    TRANSACTION_ID  VARCHAR(36)     NOT NULL,
    DISPUTE_TYPE    VARCHAR(16)     NOT NULL,
    AMOUNT          NUMBER(12,2)    NOT NULL,
    OPENED_AT       DATE            NOT NULL,
    RESOLVED_AT     DATE,
    OUTCOME         VARCHAR(16),
    SOURCE_SYSTEM   VARCHAR(16)     NOT NULL,
    CREATED_AT      TIMESTAMP_LTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS PARTNER (
    PARTNER_ID      VARCHAR(36)     NOT NULL PRIMARY KEY,
    NAME            VARCHAR(128)    NOT NULL,
    PARTNER_TYPE    VARCHAR(16)     NOT NULL,
    CONTRACT_START  DATE            NOT NULL,
    CONTRACT_END    DATE,
    STATUS          VARCHAR(16)     NOT NULL,
    SOC2_VERIFIED   BOOLEAN         NOT NULL DEFAULT FALSE,
    CREATED_AT      TIMESTAMP_LTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP()
);
